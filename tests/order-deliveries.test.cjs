const { test } = require('node:test')
const assert = require('node:assert/strict')
const { transition, proposal, projectOrder, orderStatus } = require('../backend/order-deliveries')

const initial = { estado: 'aguardando_proposta', versao: 0, proposta: null, acordo: null, despacho: null }
const offer = { acao: 'propor', versao: 0, modalidade: 'entrega', valor_frete: '12.50', prazo: 'Até três dias úteis', observacoes: 'Conforme combinado pelo chat.' }
const step = (state, input, role) => transition(state, input, role, '2026-10-15T12:00:00Z')

test('acordo exige vendedor, aceite versionado e confirmação do comprador após envio', () => {
  const proposed = step(initial, offer, 'vendedor')
  assert.equal(proposed.proposta.valor_frete, 12.5); assert.equal(proposed.versao, 1)
  assert.equal(proposed.acordo, null)
  const revised = step(proposed, { ...offer, versao: 1, valor_frete: 20, observacoes: 'Nova condição\nCom prazo revisado.' }, 'vendedor')
  assert.equal(revised.versao, 2); assert.equal(revised.proposta.valor_frete, 20)
  assert.throws(() => step(revised, { acao: 'aceitar', versao: 1 }, 'comprador'), { status: 409 })
  assert.throws(() => step(proposed, { acao: 'aceitar', versao: 0 }, 'comprador'), { status: 409 })
  assert.throws(() => step(proposed, { acao: 'despachar', versao: 1 }, 'vendedor'), { status: 409 })
  const accepted = step(proposed, { acao: 'aceitar', versao: 1 }, 'comprador')
  assert.equal(accepted.acordo.versao_proposta, 1); assert.equal(accepted.acordo.valor_frete, 12.5)
  assert.throws(() => step(accepted, { acao: 'receber', versao: 2 }, 'comprador'), { status: 409 })
  assert.throws(() => step(accepted, { ...offer, versao: 2 }, 'vendedor'), { status: 409 })
  const sent = step(accepted, { acao: 'despachar', versao: 2, codigo_rastreio: 'TESTE123' }, 'vendedor')
  assert.equal(sent.estado, 'enviado')
  const received = step(sent, { acao: 'receber', versao: 3 }, 'comprador')
  assert.equal(received.estado, 'recebido'); assert.ok(received.recebido_em)
  assert.throws(() => step(received, { acao: 'receber', versao: 4 }, 'comprador'), { status: 409 })
})

test('recusa permite nova proposta e retirada não utiliza frete nem rastreamento', () => {
  const proposed = step(initial, offer, 'vendedor')
  const refused = step(proposed, { acao: 'recusar', versao: 1 }, 'comprador')
  assert.equal(refused.estado, 'aguardando_proposta'); assert.equal(refused.acordo, null)
  const pickup = step(refused, { ...offer, versao: 2, modalidade: 'retirada', valor_frete: 0 }, 'vendedor')
  const accepted = step(pickup, { acao: 'aceitar', versao: 3 }, 'comprador')
  assert.throws(() => step(accepted, { acao: 'despachar', versao: 4, codigo_rastreio: 'nao-usar' }, 'vendedor'), { status: 400 })
  const ready = step(accepted, { acao: 'despachar', versao: 4 }, 'vendedor')
  assert.equal(ready.estado, 'pronto_retirada')
  assert.equal(step(ready, { acao: 'receber', versao: 5 }, 'comprador').estado, 'recebido')
})

test('papéis, valores e campos extras não podem alterar preço ou pagamento por fora do fluxo', () => {
  assert.throws(() => step(initial, offer, 'comprador'), { status: 403 })
  for (const raw of [null, '', true, {}, -1, 0.001, '1.234', '1e2', 100001]) assert.throws(() => proposal({ ...offer, valor_frete: raw }), { status: 400 })
  assert.equal(proposal({ ...offer, valor_frete: 0 }).valor_frete, 0)
  assert.throws(() => proposal({ ...offer, modalidade: 'retirada', valor_frete: 10 }), { status: 400 })
  for (const extra of [{ status_pagamento: 'pago' }, { comprador_id: 3 }, { total: 0 }, { prazo: '<script>' }]) assert.throws(() => step(initial, { ...offer, ...extra }, 'vendedor'), { status: 400 })
})

test('visões isolam vendedores, somam apenas acordos aceitos e liberam endereço só após aceite', () => {
  const order = { id_pedido: 1, comprador_id: 9, total: 300, status_pagamento: 'nao_iniciado', endereco_entrega: JSON.stringify({ cidade: 'Cidade teste', logradouro: 'Endereço privado do comprador' }), entrega: [2, 3].map((seller, index) => ({ grupo_id: `${seller}:${index + 1}`, vendedor_id: seller, vendedor: `Loja ${seller}`, tipo: 'a_combinar', valor: null })) }
  const items = [2, 3].map((seller, index) => ({ id_item: index + 1, vendedor_id: seller, preco_unitario: seller === 2 ? 100 : 200, quantidade: 1, nome_produto: `Produto ${seller}`, origem_envio: 'ENDERECO PRIVADO VENDEDOR' }))
  const record = state => ({ id: 1, pedido_id: 1, vendedor_id: 2, grupo_id: '2:1', estado: state.estado, versao: state.versao, dados: JSON.stringify(state) })
  const proposed = step(initial, offer, 'vendedor')
  const before = projectOrder(order, items, [record(proposed)], 2)
  assert.equal(before.itens.length, 1); assert.equal(before.total_parcial, 100); assert.equal(before.endereco_entrega, null)
  assert.equal(before.entregas.length, 1); assert.equal(before.entregas[0].acordo, null)
  for (const secret of ['Produto 3', 'Endereço privado do comprador', 'ENDERECO PRIVADO VENDEDOR']) assert.ok(!JSON.stringify(before).includes(secret))
  const accepted = step(proposed, { acao: 'aceitar', versao: 1 }, 'comprador')
  const buyer = projectOrder(order, items, [record(accepted)], 9)
  assert.equal(buyer.frete_pendente, true); assert.equal(buyer.frete_conhecido, 12.5); assert.equal(buyer.total_parcial, 312.5)
  const seller = projectOrder(order, items, [record(accepted)], 2)
  assert.equal(seller.total, 112.5); assert.ok(seller.endereco_entrega)
  assert.equal(projectOrder(order, items, [record(accepted)], 3).endereco_entrega, null)
  assert.throws(() => projectOrder(order, items, [], 99), { status: 404 })
  assert.equal(orderStatus([{ estado: 'recebido', acordo: {} }, { estado: 'enviado', acordo: {} }]), 'em_entrega')
  assert.equal(orderStatus([{ estado: 'recebido', acordo: {} }, { estado: 'recebido', acordo: {} }]), 'concluido')
  assert.equal(order.entrega[0].valor, null)
  assert.equal(projectOrder({ ...order, status: 'concluido', entrega: [] }, items, [], 9).status, 'concluido')
})
