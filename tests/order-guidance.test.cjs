const { test } = require('node:test')
const assert = require('node:assert/strict')

test('orientação distingue comprador, vendedor, envio e retirada sem concluir antes de receber', async () => {
  const { deliveryGuidance, deliveryCount } = await import('../src/lib/order-guidance.mjs')
  const guidance = (estado, role = 'comprador', modalidade = 'entrega') => deliveryGuidance({ estado, acordo: { modalidade } }, role)
  assert.match(guidance('aguardando_proposta').title, /Aguarde/)
  assert.match(guidance('aguardando_proposta', 'vendedor').title, /envie uma proposta/)
  assert.match(guidance('proposta_enviada').title, /Revise/)
  assert.match(guidance('proposta_enviada', 'vendedor').title, /Aguarde/)
  assert.match(guidance('acordo_confirmado').title, /Aguarde/)
  assert.match(guidance('acordo_confirmado', 'vendedor', 'retirada').title, /Prepare/)
  assert.match(guidance('enviado').detail, /Confirmar recebimento/)
  assert.match(guidance('enviado', 'vendedor').detail, /não precisa pedir um código/)
  assert.match(guidance('pronto_retirada', 'comprador', 'retirada').detail, /Não informe o código antecipadamente/)
  assert.match(guidance('pronto_retirada', 'vendedor', 'retirada').title, /valide o código/)
  for (const estado of ['aguardando_proposta', 'proposta_enviada', 'acordo_confirmado', 'enviado', 'pronto_retirada']) assert.ok(guidance(estado).step < 3)
  assert.equal(guidance('recebido').step, 3)
  assert.match(guidance('recebido').detail, /Relatar problema/)
  assert.equal(guidance('desconhecido').step, null)
  assert.equal(deliveryCount([]), 'Sem entrega física para acompanhar')
  assert.equal(deliveryCount([{ estado: 'recebido' }, { estado: 'enviado' }]), '1 de 2 entregas recebidas')
  assert.equal(deliveryCount([{ estado: 'recebido' }]), '1 de 1 entrega recebida')
})

test('resposta incerta exige consultar pedido; validação recusada permite corrigir os campos', async () => {
  const { uncertainOrderChange } = await import('../src/lib/order-guidance.mjs')
  for (const error of [{ status: 0 }, { status: 409 }, { status: 500 }, { status: 504 }, { status: 200, code: 'INVALID_RESPONSE' }]) assert.equal(uncertainOrderChange(error), true)
  for (const status of [400, 401, 403, 404, 429]) assert.equal(uncertainOrderChange({ status }), false)
})
