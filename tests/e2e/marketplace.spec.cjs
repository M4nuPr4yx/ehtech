const { test, expect } = require('@playwright/test')
const password = process.env.E2E_PASSWORD
async function register(page, name) {
  await page.goto('/?login=1')
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Cadastro', exact: true }).click()
  await dialog.getByLabel('Nome de Usuário').fill(name)
  await dialog.getByLabel('E-mail', { exact: true }).fill(`${name}@gmail.com`)
  await dialog.getByLabel('Senha', { exact: true }).fill(password)
  await dialog.getByLabel('Confirmar Senha', { exact: true }).fill(password)
  await dialog.getByRole('button', { name: 'Cadastrar', exact: true }).click()
  await expect(dialog.getByRole('heading')).toHaveText('Entrar no EHtech')
  await dialog.getByLabel('Senha', { exact: true }).fill(password)
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(dialog).toBeHidden()
  return page.evaluate(() => JSON.parse(atob(localStorage.getItem('token').split('.')[1])).id)
}
async function address(page) {
  await page.getByRole('button', { name: '+ Novo endereço', exact: true }).click()
  await page.locator('#address-destinatario').fill('Pessoa Fictícia Teste')
  await page.locator('#address-telefone').fill('11999991234')
  await page.locator('#address-identificacao').fill('Casa de teste')
  await page.locator('#address-cep').fill('01001000')
  await expect(page.locator('#address-cidade')).toHaveValue('São Paulo')
  await page.locator('#address-numero').fill('100')
  const saved = page.waitForResponse(response => new URL(response.url()).pathname === '/api/enderecos' && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Salvar e revisar', exact: true }).click()
  expect((await saved).status()).toBe(201)
  await page.getByRole('button', { name: 'Confirmar endereço', exact: true }).click()
}

test.beforeEach(async ({ request }) => {
  const reset = await request.post(`${process.env.E2E_API_URL}/__e2e/reset-limits`, { headers: { 'x-e2e-key': process.env.E2E_RESET_KEY } })
  expect(reset.ok()).toBeTruthy()
})
test('jornada real: anunciar, aprovar, comprar, receber, avaliar e moderar', async ({ page, browser }, info) => {
  const options = { baseURL: process.env.E2E_BASE_URL, viewport: page.viewportSize(), isMobile: Boolean(info.project.use.isMobile), hasTouch: Boolean(info.project.use.hasTouch) }
  const sellerContext = await browser.newContext(options), adminContext = await browser.newContext(options)
  const seller = await sellerContext.newPage(), admin = await adminContext.newPage()
  const suffix = info.project.name, name = `Notebook E2E ${suffix}`
  let productId, orderPath, buyerId, sellerId
  try {
    await test.step('Cadastrar vendedor, salvar origem e enviar anúncio para aprovação', async () => {
      sellerId = await register(seller, `vendedor_${suffix}`)
      await seller.goto('/perfil?aba=enderecos')
      await address(seller)
      await seller.goto('/anunciar')
      await seller.locator('#product-name').fill(name)
      await seller.locator('#product-price').fill('150000')
      await seller.locator('#product-stock').fill('3')
      await seller.locator('#product-category').selectOption('notebooks')
      await seller.locator('#product-description').fill('Notebook fictício para teste completo do marketplace, com memória de 16 GB e SSD de 512 GB.')
      await expect.poll(() => seller.evaluate(() => Object.keys(sessionStorage).some(key => key.startsWith('ehtech-anuncio-rascunho-')))).toBeTruthy()
      await seller.reload()
      await expect(seller.locator('#product-name')).toHaveValue(name)
      await expect(seller.getByText('Rascunho de texto restaurado.')).toBeVisible()
      await seller.getByRole('button', { name: 'Selecionar ou cadastrar endereço', exact: true }).click()
      await seller.getByRole('button', { name: 'Selecionar e revisar', exact: true }).click()
      await seller.getByRole('button', { name: 'Confirmar endereço', exact: true }).click()
      const created = seller.waitForResponse(response => new URL(response.url()).pathname === '/api/produtos' && response.request().method() === 'POST')
      await seller.getByRole('button', { name: 'Publicar Anúncio', exact: true }).click()
      const response = await created; expect(response.status()).toBe(201); productId = (await response.json()).id
      await expect(seller.getByText('Produto enviado com sucesso! O anúncio aguarda aprovação da moderação.')).toBeVisible()
    })
    await test.step('Administrador aprova o anúncio pela interface', async () => {
      await admin.goto('/admin')
      await admin.getByLabel('E-mail Administrativo').fill(process.env.E2E_ADMIN_EMAIL)
      await admin.getByLabel('Senha', { exact: true }).fill(password)
      await admin.getByRole('button', { name: 'Entrar como Administrador' }).click()
      const heading = admin.getByRole('heading', { name, exact: true })
      const approved = admin.waitForResponse(response => response.url().includes(`/admin/produtos/${productId}/aprovacao`))
      await heading.locator('../../..').getByRole('button', { name: 'Aprovar', exact: true }).click()
      expect((await approved).status()).toBe(200)
    })
    await test.step('Cadastrar comprador, favoritar, comparar e impedir avaliação prematura', async () => {
      buyerId = await register(page, `comprador_${suffix}`)
      await page.goto(`/produtos/${productId}`)
      await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
      await expect(page.getByText('Somente compradores com pedido concluído e recebimento confirmado podem avaliar.')).toBeVisible()
      await expect(page.getByRole('button', { name: 'Enviar Avaliação', exact: true })).toHaveCount(0)
      await page.getByRole('button', { name: 'Salvar favorito', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Remover dos favoritos', exact: true })).toBeVisible()
      await page.getByRole('button', { name: 'Comparar anúncio', exact: true }).click()
      await page.goto('/favoritos')
      await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
      await page.goto('/comparar')
      await expect(page.getByRole('table')).toContainText(name)
      await expect(page.getByRole('table')).toContainText('16 GB')
      await page.screenshot({ path: info.outputPath('comparacao.png'), fullPage: true })
    })
    await test.step('Carrinho, endereço, revisão e registro de pedido sem cobrança', async () => {
      await page.goto(`/produtos/${productId}`)
      await page.getByRole('button', { name: 'Adicionar ao Carrinho', exact: true }).click()
      await page.getByRole('button', { name: 'Comprar agora', exact: true }).click()
      await expect(page).toHaveURL(/\/checkout$/)
      expect(await page.evaluate(() => JSON.parse(localStorage.getItem('cart'))[0].quantidade)).toBe(1)
      await page.goto('/carrinho')
      await page.getByRole('button', { name: 'Finalizar compra', exact: true }).click()
      await address(page)
      await expect(page.getByRole('radio')).toBeChecked()
      await expect(page.getByRole('button', { name: 'Continuar com frete a combinar', exact: true })).toBeEnabled()
      await page.getByRole('link', { name: 'Conversar antes de continuar (opcional) →', exact: true }).click()
      await expect(page).toHaveURL(/\/mensagens\?usuario=/)
      await page.goBack()
      await expect(page).toHaveURL(/\/checkout$/)
      await expect(page.getByRole('radio')).toBeChecked()
      await page.reload()
      await expect(page.getByRole('radio')).toBeChecked()
      await page.getByRole('button', { name: 'Continuar com frete a combinar', exact: true }).click()
      await expect(page).toHaveURL(/\/checkout$/)
      await expect(page.getByRole('heading', { name: 'Pagamento e revisão final', exact: true })).toBeVisible()
      await page.screenshot({ path: info.outputPath('compra-frete-a-combinar.png'), fullPage: true })
      const registered = page.waitForResponse(response => new URL(response.url()).pathname === '/api/pedidos' && response.request().method() === 'POST')
      await page.getByRole('button', { name: 'Confirmar e registrar pedido', exact: true }).click()
      const orderResponse = await registered
      expect(orderResponse.status()).toBe(201)
      const orderData = await orderResponse.json()
      expect(orderData.frete_pendente).toBe(true); expect(orderData.total).toBeNull(); expect(orderData.frete).toBeNull()
      expect(orderData.status_pagamento).toBe('nao_iniciado')
      await expect(page.getByText('Pagamento não iniciado. Nenhuma cobrança foi realizada.')).toBeVisible()
      await page.getByRole('link', { name: 'Acompanhar pedido e registrar acordo →' }).click()
      await expect(page).toHaveURL(/\/pedidos\/\d+$/)
      orderPath = new URL(page.url()).pathname
    })
    await test.step('Negociar retirada, aceitar proposta e confirmar recebimento', async () => {
      await seller.goto(orderPath)
      await seller.getByRole('combobox', { name: /Modalidade/ }).selectOption('retirada')
      await seller.getByLabel('Prazo combinado', { exact: true }).fill('Retirada em até três dias úteis')
      await seller.getByRole('button', { name: 'Enviar proposta', exact: true }).click()
      await expect(seller.getByText('Proposta aguardando aceite', { exact: true }).first()).toBeVisible()
      await page.reload()
      await page.getByRole('checkbox').check()
      await page.getByRole('button', { name: 'Aceitar proposta', exact: true }).click()
      await expect(page.getByRole('heading', { name: 'Acordo confirmado', exact: true })).toBeVisible()
      await seller.reload()
      await seller.getByRole('button', { name: 'Marcar pronto para retirada', exact: true }).click()
      await expect(seller.getByText('Pronto para retirada', { exact: true }).first()).toBeVisible()
      await page.reload()
      await page.getByRole('checkbox', { name: /Já recebi os produtos e quero gerar o código/ }).check()
      const codeResponse = page.waitForResponse(response => response.url().endsWith('/codigo') && response.request().method() === 'POST')
      await page.getByRole('button', { name: 'Gerar código após receber', exact: true }).click()
      const code = (await (await codeResponse).json()).codigo
      await seller.getByLabel('Código de seis dígitos', { exact: true }).fill(code)
      await seller.getByRole('button', { name: 'Validar código e registrar recebimento', exact: true }).click()
      await expect(seller.getByRole('heading', { name: 'Pedido concluído', exact: true })).toBeVisible()
      await page.reload()
      await expect(page.getByRole('heading', { name: 'Pedido concluído', exact: true })).toBeVisible()
    })
    await test.step('Avaliação de compra verificada', async () => {
      await page.goto(`/produtos/${productId}`)
      await page.getByRole('button', { name: 'Avaliar com 5 estrelas', exact: true }).click()
      await page.getByLabel('Comentário da avaliação').fill('Produto recebido, avaliação de compra verificada no teste.')
      await page.getByRole('button', { name: 'Enviar Avaliação', exact: true }).click()
      await expect(page.getByText('Compra verificada', { exact: true })).toBeVisible()
    })
    await test.step('Denunciar conteúdo e bloquear mensagens sem apagar histórico', async () => {
      await seller.goto(`/mensagens?usuario=${buyerId}`)
      await seller.getByLabel('Digite sua mensagem', { exact: true }).fill('Mensagem fictícia para testar denúncia e bloqueio.')
      await seller.getByRole('button', { name: 'Enviar mensagem', exact: true }).click()
      await expect(seller.getByText('Mensagem fictícia para testar denúncia e bloqueio.', { exact: true }).last()).toBeVisible()
      await page.goto(`/mensagens?usuario=${sellerId}`)
      await page.getByRole('button', { name: 'Denunciar mensagem', exact: true }).click()
      await page.getByLabel('Descreva a situação').fill(`Mensagem fictícia denunciada ${suffix} para validar a fila de moderação.`)
      await page.getByRole('button', { name: 'Enviar denúncia', exact: true }).click()
      await expect(page.getByText('Denúncia registrada para análise da administração.')).toBeVisible()
      await page.getByRole('button', { name: 'Bloquear usuário', exact: true }).click()
      await expect(page.getByRole('button', { name: 'Desbloquear usuário', exact: true })).toBeVisible()
      await seller.getByLabel('Digite sua mensagem', { exact: true }).fill('Esta mensagem deve ser bloqueada pelo servidor.')
      await seller.getByRole('button', { name: 'Enviar mensagem', exact: true }).click()
      await expect(seller.getByText('Novas mensagens não estão disponíveis entre estas contas.')).toBeVisible()
      await page.goto('/bloqueados')
      await page.getByRole('button', { name: 'Desbloquear', exact: true }).click()
      await expect(page.getByText('Você não bloqueou nenhum usuário.')).toBeVisible()
    })
    await test.step('Administrador registra decisão e consulta histórico', async () => {
      await admin.goto('/admin/denuncias')
      const report = admin.getByRole('article').filter({ hasText: `Mensagem fictícia denunciada ${suffix}` })
      await report.getByLabel('Nova decisão').selectOption('resolvida')
      await report.getByLabel('Justificativa').fill('Revisão de teste concluída com orientação ao usuário.')
      await report.getByRole('button', { name: 'Registrar decisão', exact: true }).click()
      await admin.getByLabel('Filtrar por status').selectOption('resolvida')
      await expect(admin.getByText(/Administrador #\d+ · resolvida: Revisão de teste concluída/).first()).toBeVisible()
      await admin.screenshot({ path: info.outputPath('moderacao.png'), fullPage: true })
    })
    await test.step('Trocar senha pela interface revoga token anterior e permite novo login', async () => {
      const oldToken = await page.evaluate(() => localStorage.getItem('token'))
      await page.goto('/perfil')
      await page.getByRole('button', { name: 'Segurança', exact: true }).click()
      await page.getByPlaceholder('Senha atual', { exact: true }).fill(password)
      await page.getByPlaceholder('Nova senha (mínimo 8 caracteres)', { exact: true }).fill('Nova-Password-2026')
      await page.getByPlaceholder('Confirmar nova senha', { exact: true }).fill('Nova-Password-2026')
      const changed = page.waitForResponse(response => response.url().endsWith('/perfil/senha') && response.request().method() === 'PUT')
      await page.getByRole('button', { name: 'Alterar Senha', exact: true }).click()
      expect((await changed).status()).toBe(200)
      const rejected = await page.request.get(`${process.env.E2E_API_URL}/perfil`, { headers: { Authorization: `Bearer ${oldToken}` } })
      expect(rejected.status()).toBe(403)
      await expect.poll(() => page.evaluate(() => localStorage.getItem('token'))).toBeNull()
      await page.goto('/?login=1')
      const dialog = page.getByRole('dialog')
      await dialog.getByLabel('E-mail', { exact: true }).fill(`comprador_${suffix}@gmail.com`)
      await dialog.getByLabel('Senha', { exact: true }).fill('Nova-Password-2026')
      await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
      await expect(dialog).toBeHidden()
      await page.goto('/favoritos')
      await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
    })
  } finally { await Promise.allSettled([sellerContext.close(), adminContext.close()]) }
})
